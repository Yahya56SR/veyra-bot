import { build } from 'esbuild';
import { existsSync, readdirSync, statSync } from 'node:fs';

/**
 * Builds the single-file bot bundle committed at the repository root.
 *
 * The production host (256 MB free tier) cannot run `npm install`, so every
 * runtime dependency except a few optional native addons is bundled here.
 */
const EXTERNALS = [
  // Optional native accelerators that ws/discord.js probe with require().
  'zlib-sync',
  'bufferutil',
  'utf-8-validate',
  'erlpack',
  // Optional voice/crypto addons; Lavalink handles audio, so these stay out.
  '@discordjs/opus',
  'sodium-native',
  // Dev-only log formatter.
  'pino-pretty',
];

const MAX_BUNDLE_BYTES = 20 * 1024 * 1024;

await build({
  entryPoints: ['apps/bot/src/index.ts'],
  outfile: 'index.js',
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'cjs',
  keepNames: true,
  sourcemap: false,
  legalComments: 'eof',
  logLevel: 'info',
  external: EXTERNALS,
  banner: {
    js: '// Generated by scripts/bundle-bot.mjs — do not edit. Source: apps/bot/src',
  },
});

const bytes = statSync('index.js').size;
const megabytes = bytes / 1024 / 1024;

console.log(`bundle: ${megabytes.toFixed(2)} MB (index.js)`);

if (!existsSync('drizzle')) {
  console.warn('warning: drizzle/ is missing; the host cannot migrate without it');
} else {
  const migrations = readdirSync('drizzle').filter((file) => file.endsWith('.sql'));
  console.log(`migrations: ${migrations.length} file(s) in drizzle/`);
  if (migrations.length === 0) {
    console.warn('warning: no .sql migrations found; run `npm run db:generate`');
  }
}

if (bytes > MAX_BUNDLE_BYTES) {
  console.error(`Bundle is larger than the ${MAX_BUNDLE_BYTES / 1024 / 1024} MB gate.`);
  process.exit(1);
}
